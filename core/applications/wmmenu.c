#define _POSIX_C_SOURCE 200809L
#include "wmmenu.h"
#include <stdlib.h>
#include <string.h>
#include <strings.h>

static int cmp_name(const void *a, const void *b) {
    int c = strcasecmp(((const WMApp *)a)->name, ((const WMApp *)b)->name);
    return c ? c : strcmp(((const WMApp *)a)->id, ((const WMApp *)b)->id);     /* stable output */
}

char *wmmenu_wm_escape(const char *cmd) {
    char *out = malloc(strlen(cmd) * 2 + 1), *w = out; if (!out) abort();
    for (; *cmd; cmd++) {
        if (*cmd == '\\') { *w++ = '\\'; *w++ = '\\'; }
        else if (*cmd == '%') { *w++ = '\\'; *w++ = '%'; }
        else *w++ = *cmd;
    }
    *w = 0; return out;
}

void wmmenu_plist_string(FILE *o, const char *s) {
    fputc('"', o);
    for (; *s; s++) {
        switch (*s) {
        case '"': case '\\': fputc('\\', o); fputc(*s, o); break;
        case '\n': fputs("\\n", o); break;
        case '\t': fputs("\\t", o); break;
        case '\r': fputs("\\r", o); break;
        default: fputc(*s, o);
        }
    }
    fputc('"', o);
}

static void emit_command(FILE *o, const WMApp *a, const char *term) {
    char *cmd = wmapps_shell_command(a, NULL, 0, term), *e = wmmenu_wm_escape(cmd);
    free(cmd);
    wmmenu_plist_string(o, e); free(e);
}

void wmmenu_emit_applications(FILE *o, WMAppRegistry *r, const char *term) {
    if (!term) term = "xterm -e";
    qsort(r->apps, r->count, sizeof *r->apps, cmp_name);
    fputs("(\"Applications\"", o);
    for (int c = 0; wmapps_category_names[c]; c++) {
        int any = 0;
        for (size_t i = 0; i < r->count; i++) {
            const WMApp *a = &r->apps[i];
            if (strcmp(a->category, wmapps_category_names[c])) continue;
            if (!any) { fprintf(o, ",\n (\"%s\"", wmapps_category_names[c]); any = 1; }
            fputs(",\n  (", o); wmmenu_plist_string(o, a->name); fputs(", SHEXEC, ", o);
            emit_command(o, a, term);
            fputc(')', o);
        }
        if (any) fputc(')', o);
    }
    fputc(')', o);
}

static const char *default_template =
    "(\"Window Maker\",\n"
    "@APPLICATIONS@,\n"
    " (\"Run...\", SHEXEC, \"%a(Run,Type command to run:)\"),\n"
    " (\"Workspaces\", WORKSPACE_MENU),\n"
    " (\"Appearance\", OPEN_MENU, \"appearance.menu\"),\n"
    " (\"Session\",\n"
    "  (\"Restart Window Maker\", RESTART),\n"
    "  (\"Exit\", EXIT)))\n";

void wmmenu_emit_root(FILE *o, WMAppRegistry *r, const char *term, const char *tmpl) {
    fprintf(o, "// Generated by wmmenud - edit your template, not this file.\n");
    if (!tmpl) tmpl = default_template;
    for (const char *p = tmpl; *p;) {
        const char *nl = strchr(p, '\n'); size_t len = nl ? (size_t)(nl - p) : strlen(p);
        const char *mark = strstr(p, "@APPLICATIONS@");
        if (mark && mark >= p + len) mark = NULL;     /* found on a later line */
        if (mark) {
            fwrite(p, 1, (size_t)(mark - p), o);
            wmmenu_emit_applications(o, r, term);
            fwrite(mark + 14, 1, len - (size_t)(mark - p) - 14, o);
        } else fwrite(p, 1, len, o);
        if (nl) { fputc('\n', o); p = nl + 1; } else break;
    }
}
