#define _POSIX_C_SOURCE 200809L
/* wmgfx - detect the GPU driver and emit a tear-free X11 setup.
 *
 *   wmgfx detect              drivers found, one per line, plus the chosen primary
 *   wmgfx xorg                xorg.conf.d snippet (needs root to install: see --system)
 *   wmgfx picom               picom.conf tuned for the detected driver
 *   wmgfx apply [--system]    write ~/.config/picom/picom.conf (and, with --system,
 *                             /etc/X11/xorg.conf.d/20-wm-desktop-gpu.conf)
 *   wmgfx autostart           one-line command for your Window Maker autostart
 *
 * No distro assumptions: reads /sys/class/drm only. WMGFX_SYSFS overrides the root for tests. */
#include <dirent.h>
#include <errno.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <unistd.h>

typedef enum { G_NONE, G_AMDGPU, G_RADEON, G_INTEL, G_NOUVEAU, G_NVIDIA, G_OTHER } Gpu;
static const char *gpu_name[] = { "none", "amdgpu", "radeon", "intel", "nouveau", "nvidia", "other" };

static Gpu classify(const char *drv) {
    if (!strcmp(drv, "amdgpu")) return G_AMDGPU;
    if (!strcmp(drv, "radeon")) return G_RADEON;
    if (!strcmp(drv, "i915") || !strcmp(drv, "xe")) return G_INTEL;
    if (!strcmp(drv, "nouveau")) return G_NOUVEAU;
    if (!strcmp(drv, "nvidia")) return G_NVIDIA;
    return G_OTHER;
}

/* Collect distinct drivers of real cards (card0, card1 - not card0-HDMI-A-1 connectors). */
static int detect(Gpu *found, int max) {
    const char *root = getenv("WMGFX_SYSFS"); if (!root) root = "/sys";
    char dir[1024]; snprintf(dir, sizeof dir, "%s/class/drm", root);
    DIR *d = opendir(dir); int n = 0; if (!d) return 0;
    struct dirent *e;
    while ((e = readdir(d))) {
        if (strncmp(e->d_name, "card", 4) || strchr(e->d_name + 4, '-') || !e->d_name[4]) continue;
        char link[1400], tgt[512];
        snprintf(link, sizeof link, "%s/%s/device/driver", dir, e->d_name);
        ssize_t k = readlink(link, tgt, sizeof tgt - 1); if (k < 0) continue;
        tgt[k] = 0; const char *base = strrchr(tgt, '/'); base = base ? base + 1 : tgt;
        Gpu g = classify(base); int dup = 0;
        for (int i = 0; i < n; i++) if (found[i] == g) dup = 1;
        if (!dup && n < max) found[n++] = g;
    }
    closedir(d); return n;
}

/* Hybrid laptops: prefer the GPU that drives the panel, i.e. integrated first. */
static Gpu primary(const Gpu *f, int n) {
    static const Gpu order[] = { G_AMDGPU, G_INTEL, G_NVIDIA, G_NOUVEAU, G_RADEON, G_OTHER };
    for (unsigned o = 0; o < sizeof order / sizeof *order; o++)
        for (int i = 0; i < n; i++) if (f[i] == order[o]) return f[i];
    return G_NONE;
}

static void emit_xorg(FILE *o, Gpu g) {
    fputs("# Generated by wmgfx. Tear-free configuration for your GPU driver.\n", o);
    switch (g) {
    case G_AMDGPU:
        fputs("Section \"Device\"\n    Identifier \"wm-desktop-amd\"\n    Driver \"amdgpu\"\n"
              "    Option \"TearFree\" \"true\"\n    Option \"DRI\" \"3\"\nEndSection\n", o); break;
    case G_RADEON:
        fputs("Section \"Device\"\n    Identifier \"wm-desktop-radeon\"\n    Driver \"radeon\"\n"
              "    Option \"TearFree\" \"on\"\nEndSection\n", o); break;
    case G_INTEL:
        fputs("# Modern Intel uses the generic modesetting driver, which has no TearFree\n"
              "# option; tearing is handled by the compositor (picom, glx + vsync).\n"
              "# Only needed if you installed the legacy xf86-video-intel driver:\n"
              "# Section \"Device\"\n#     Identifier \"wm-desktop-intel\"\n#     Driver \"intel\"\n"
              "#     Option \"TearFree\" \"true\"\n# EndSection\n", o); break;
    case G_NVIDIA:
        fputs("Section \"Screen\"\n    Identifier \"wm-desktop-nvidia\"\n    Option \"metamodes\" "
              "\"nvidia-auto-select +0+0 {ForceFullCompositionPipeline=On}\"\n"
              "    Option \"AllowIndirectGLXProtocol\" \"off\"\nEndSection\n", o); break;
    default:
        fputs("# No driver-level option known for this GPU; the compositor handles vsync.\n", o);
    }
}

static void emit_picom(FILE *o, Gpu g) {
    fputs("# Generated by wmgfx. Minimal on purpose: vsync, no eye candy, Window Maker look intact.\n", o);
    fputs("backend = \"glx\";\nvsync = true;\n", o);
    fputs("glx-no-stencil = true;\nglx-no-rebind-pixmap = true;\nuse-damage = true;\n", o);
    if (g == G_NVIDIA) fputs("# NVIDIA: damage tracking can glitch with the proprietary driver\nuse-damage = false;\n", o);
    fputs("shadow = false;\nfading = false;\n"
          "unredir-if-possible = false;   # keep fullscreen windows vsynced too\n"
          "detect-client-opacity = true;\n"
          "detect-rounded-corners = false;\n", o);
}

static int mkpath(const char *path) {          /* mkdir -p of dirname(path) */
    char buf[4096]; snprintf(buf, sizeof buf, "%s", path);
    for (char *p = buf + 1; *p; p++) if (*p == '/') { *p = 0; mkdir(buf, 0755); *p = '/'; }
    return 0;
}

static int write_to(const char *path, void (*fn)(FILE *, Gpu), Gpu g) {
    mkpath(path);
    FILE *f = fopen(path, "w");
    if (!f) { fprintf(stderr, "wmgfx: %s: %s\n", path, strerror(errno)); return 1; }
    fn(f, g); fclose(f); fprintf(stderr, "wmgfx: wrote %s\n", path); return 0;
}

int main(int argc, char **argv) {
    if (argc < 2) { fputs("usage: wmgfx detect|xorg|picom|apply [--system]|autostart\n", stderr); return 2; }
    Gpu found[8]; int n = detect(found, 8); Gpu g = primary(found, n);
    if (!strcmp(argv[1], "detect")) {
        for (int i = 0; i < n; i++) printf("driver: %s\n", gpu_name[found[i]]);
        printf("primary: %s\n", gpu_name[g]);
    } else if (!strcmp(argv[1], "xorg")) emit_xorg(stdout, g);
    else if (!strcmp(argv[1], "picom")) emit_picom(stdout, g);
    else if (!strcmp(argv[1], "autostart")) puts("picom --daemon");
    else if (!strcmp(argv[1], "apply")) {
        const char *x = getenv("XDG_CONFIG_HOME"), *h = getenv("HOME"); char p[4096];
        if (x && *x) snprintf(p, sizeof p, "%s/picom/picom.conf", x);
        else snprintf(p, sizeof p, "%s/.config/picom/picom.conf", h ? h : "");
        int rc = write_to(p, emit_picom, g);
        if (argc > 2 && !strcmp(argv[2], "--system"))
            rc |= write_to("/etc/X11/xorg.conf.d/20-wm-desktop-gpu.conf", emit_xorg, g);
        else if (g == G_AMDGPU || g == G_RADEON || g == G_NVIDIA)
            fputs("wmgfx: driver-level tear-free needs root: rerun with `apply --system`, or\n"
                  "       `wmgfx xorg | sudo tee /etc/X11/xorg.conf.d/20-wm-desktop-gpu.conf`\n", stderr);
        return rc;
    } else { fprintf(stderr, "unknown command %s\n", argv[1]); return 2; }
    return 0;
}
